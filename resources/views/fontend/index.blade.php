    document.addEventListener("DOMContentLoaded", function () {
        var currencyItems = document.querySelectorAll(".dpackage-section__currency-item");
        var priceCurrencyItems = document.querySelectorAll(".dpackage-price_currency");
        var prices = document.querySelectorAll(".dpackage-price");
        var priceHours = document.querySelectorAll(".dpackage-pricehour");
        var oldPrices = document.querySelectorAll(".dpackage-oldprice");
        var items = document.querySelectorAll(".dpackage-sale__item");
        var itemparent = document.querySelector(".web3package-section__list");
        var allparent = document.querySelector(".nsprice");

        var activeCurrency = "usd";
        var activeMonth = 3;

        const enterprisePrice = document.querySelector(".enterprise-price");

        function updatePrices(month) {
            var basePrice, baseHour;

            if (enterprisePrice) {
                const newPrice = enterprisePrice.getAttribute(`data-price${activeCurrency}`);
                if (newPrice) {
                    enterprisePrice.textContent = newPrice;
                }
            }

            prices.forEach(function (price, index) {
                var initialPrice = parseInt(price.getAttribute("data-pricew2")) / 3;
                var initialHour = parseInt(priceHours[index].getAttribute("data-hourw2"));

                if (activeCurrency === "eur") {
                    basePrice = parseInt(price.getAttribute("data-priceeur"));
                    baseHour = parseInt(priceHours[index].getAttribute("data-houreur"));
                    allparent.classList.add("show-txt");
                } else if (activeCurrency === "gbp") {
                    basePrice = parseInt(price.getAttribute("data-pricegbp"));
                    baseHour = parseInt(priceHours[index].getAttribute("data-hourgbp"));
                    allparent.classList.add("show-txt");
                } else {
                    basePrice = parseInt(price.getAttribute("data-pricew2"));
                    baseHour = parseInt(priceHours[index].getAttribute("data-hourw2"));
                    allparent.classList.remove("show-txt");
                }

                if (month === 6) {
                    price.textContent = Math.round(basePrice * 2 * 0.9 / 6);
                    priceHours[index].textContent = Math.round(baseHour * 0.9);
                    itemparent.classList.add("saleactive");
                } else if (month === 12) {
                    price.textContent = Math.round(basePrice * 4 * 0.8 / 12);
                    priceHours[index].textContent = Math.round(baseHour * 0.8);
                    itemparent.classList.add("saleactive");
                } else {
                    price.textContent = basePrice / 3;
                    priceHours[index].textContent = baseHour;
                    itemparent.classList.remove("saleactive");
                }
            });

            updateCurrencyClass();

            updateOldPrices();
        }

        function updateOldPrices() {
            oldPrices.forEach(function (oldPrice) {
                var oldPriceValue;

                if (activeCurrency === "eur") {
                    oldPriceValue = oldPrice.getAttribute("data-oldeur");
                } else if (activeCurrency === "gbp") {
                    oldPriceValue = oldPrice.getAttribute("data-oldegbp");
                } else {
                    oldPriceValue = oldPrice.getAttribute("data-old");
                }

                oldPrice.textContent = oldPriceValue;
            });
        }

        currencyItems.forEach(function (currencyItem) {
            currencyItem.addEventListener("click", function () {
                currencyItems.forEach(function (currency) {
                    currency.classList.remove("active");
                });
                currencyItem.classList.add("active");
                activeCurrency = currencyItem.getAttribute("data-curr");
                updatePrices(activeMonth);
            });
        });

        function updateCurrencyClass() {
            priceCurrencyItems.forEach(function (currencyItem) {
                currencyItem.classList.remove("active");
                if (currencyItem.getAttribute("data-curr") === activeCurrency) {
                    currencyItem.classList.add("active");
                }
            });
        }

        items.forEach(function (item) {
            item.addEventListener("click", function () {
                var month = parseInt(this.getAttribute("data-month"));
                activeMonth = month;
                updatePrices(month);

                items.forEach(function (item) {
                    item.classList.remove("active");
                });
                this.classList.add("active");
            });
        });

        updatePrices(activeMonth);

        document.querySelector(".dpackage-section__currency-item.usd").classList.add("active");
    });

